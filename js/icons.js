    'C9.8 9.2 10.4 10.8 10.4 12.6 C11.8 10 12.8 6.5 12 1.5 Z ' +
    'M12.2 12.5 C13.8 14.6 15 16.2 15 18 C15 19.8 13.7 20.6 12 20.6 C10.3 20.6 9 19.6 9 18 ' +
    'C9 16.4 10 15.4 10.8 14.6 C11.2 15.4 11.4 15.9 11.5 16.5 C12.2 15.3 12.5 14 12.2 12.5 Z';

